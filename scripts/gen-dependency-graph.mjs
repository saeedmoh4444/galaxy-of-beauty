#!/usr/bin/env node
/**
 * Workspace dependency graph generator.
 *
 * Emits docs/architecture/dependency-graph.md — a mermaid flowchart of the
 * workspace package graph: solid edges for runtime `dependencies`, dashed
 * edges for `devDependencies` (workspace: protocol only).
 *
 * Output is deterministic (no timestamps) so `--check` can verify freshness
 * in CI. CRLF checkouts (Windows) are tolerated by normalizing before compare.
 *
 * Usage:
 *   node scripts/gen-dependency-graph.mjs            # (re)generate the artifact
 *   node scripts/gen-dependency-graph.mjs --check    # exit 1 on drift
 *   node scripts/gen-dependency-graph.mjs --out path # custom output path
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { loadWorkspace } from './check-cycles.mjs';

export const HEADER = '<!-- generated by scripts/gen-dependency-graph.mjs — do not edit -->';

export const DEFAULT_OUT = path.join('docs', 'architecture', 'dependency-graph.md');

const nodeId = (name) => `pkg_${name.replaceAll(/[^a-zA-Z0-9_]/g, '_')}`;

/** Generate the markdown artifact for a loaded workspace. */
export function generateGraph(ws) {
  const packages = [...ws.packages].sort((a, b) => a.name.localeCompare(b.name));
  const lines = [
    HEADER,
    '',
    '# Workspace Dependency Graph',
    '',
    'Regenerate with `node scripts/gen-dependency-graph.mjs`. CI checks freshness (Architecture Gates job).',
    '',
    '```mermaid',
    'flowchart LR',
  ];

  const edgeLines = [];
  for (const pkg of packages) {
    for (const [dep, section] of [...pkg.workspaceDeps.entries()].sort((a, b) =>
      a[0].localeCompare(b[0]),
    )) {
      const arrow = section === 'devDependencies' ? '-.->' : '-->';
      edgeLines.push(`  ${nodeId(pkg.name)}["${pkg.name}"] ${arrow} ${nodeId(dep)}["${dep}"]`);
    }
  }
  if (edgeLines.length === 0) edgeLines.push('  %% no workspace dependencies');
  lines.push('  %% solid = runtime dependency, dashed = devDependency', ...edgeLines, '```', '');

  return lines.join('\n');
}

/** Compare generated output against the on-disk artifact (CRLF-tolerant). */
export function checkFresh(rootDir, outPath) {
  const ws = loadWorkspace(rootDir);
  const generated = generateGraph(ws);
  const absOut = path.isAbsolute(outPath) ? outPath : path.join(rootDir, outPath);
  if (!fs.existsSync(absOut)) return false;
  const existing = fs.readFileSync(absOut, 'utf8').replaceAll('\r\n', '\n');
  return existing === generated;
}

export function main() {
  const args = process.argv.slice(2);
  const checkIdx = args.indexOf('--check');
  const outIdx = args.indexOf('--out');
  const positional = [];
  for (let i = 0; i < args.length; i += 1) {
    if (args[i] === '--check') continue;
    if (args[i] === '--out') {
      i += 1;
      continue;
    }
    positional.push(args[i]);
  }
  const rootDir = path.resolve(positional[0] ?? process.cwd());
  const outPath = outIdx !== -1 && args[outIdx + 1] ? args[outIdx + 1] : DEFAULT_OUT;

  const ws = loadWorkspace(rootDir);
  if (checkIdx !== -1) {
    const fresh = checkFresh(rootDir, outPath);
    if (!fresh) {
      console.error(`FAIL: ${outPath} is out of date — run: node scripts/gen-dependency-graph.mjs`);
      process.exit(1);
    }
    console.log(`dependency graph fresh (${ws.packages.length} packages) — PASS`);
    return;
  }
  fs.writeFileSync(path.join(rootDir, outPath), generateGraph(ws));
  console.log(`wrote ${outPath} (${ws.packages.length} packages)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
