#!/usr/bin/env node
/**
 * Locale-split codegen — generates per-locale web catalogs from the 11
 * domain files (packages/shared/src/i18n/messages/*.ts), which remain the
 * single source of truth. Each domain key is `{ ar, en }`; this script
 * flattens them into packages/shared/src/i18n/messages/generated/{en,ar}.ts
 * so a web route only ships the ACTIVE locale (~60 KB gz saved per route).
 *
 * Run with Node type stripping (the domain files are plain data modules):
 *   node --experimental-strip-types scripts/generate-locale-catalogs.mjs [--check]
 *
 * `--check` regenerates in memory and exits 1 if the committed files drift.
 * The domain load order below must match the merge order in
 * packages/shared/src/i18n/web.ts (later domains override on collisions).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..');
const MESSAGES_DIR = path.join(repoRoot, 'packages/shared/src/i18n/messages');
const GENERATED_DIR = path.join(MESSAGES_DIR, 'generated');

const DOMAINS = [
  ['core', 'coreMessages'],
  ['nav', 'navMessages'],
  ['auth', 'authMessages'],
  ['booking', 'bookingMessages'],
  ['wallet', 'walletMessages'],
  ['profile', 'profileMessages'],
  ['admin', 'adminMessages'],
  ['marketing', 'marketingMessages'],
  ['ui', 'uiMessages'],
  ['misc', 'miscMessages'],
  ['bundles', 'bundlesMessages'],
];

/**
 * Flatten [{ name, catalog }] into { en, ar } string maps. Later domains
 * override earlier ones on key collisions (parity with today's object-spread
 * merge in web.ts); collisions are reported, not fatal.
 */
export function splitByLocale(domainFiles) {
  const en = {};
  const ar = {};
  const collisions = [];
  for (const { name, catalog } of domainFiles) {
    for (const [key, msg] of Object.entries(catalog)) {
      if (typeof msg?.ar !== 'string' || typeof msg?.en !== 'string') {
        throw new Error(`${name}: key '${key}' is not { ar: string; en: string }`);
      }
      if (key in en) collisions.push(`${key} (${name})`);
      en[key] = msg.en;
      ar[key] = msg.ar;
    }
  }
  return { en, ar, collisions };
}

function render(exportName, catalog) {
  const lines = Object.entries(catalog)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
  return [
    '// AUTO-GENERATED by scripts/generate-locale-catalogs.mjs — do not edit.',
    '// Regenerate: node --experimental-strip-types scripts/generate-locale-catalogs.mjs',
    '// Explicit Record annotation keeps tsc fast (no 5k-entry literal inference).',
    '',
    `export const ${exportName}: Record<string, string> = {`,
    ...lines,
    '};',
    '',
  ].join('\n');
}

async function loadDomains() {
  const out = [];
  for (const [file, exportName] of DOMAINS) {
    const url = pathToFileURL(path.join(MESSAGES_DIR, `${file}.ts`)).href;
    const mod = await import(url);
    out.push({ name: file, catalog: mod[exportName] });
  }
  return out;
}

async function main() {
  const check = process.argv.includes('--check');
  const domains = await loadDomains();
  const { en, ar, collisions } = splitByLocale(domains);
  if (collisions.length) {
    console.warn(
      `note: ${collisions.length} later-domain override(s): ${collisions.slice(0, 5).join(', ')}`,
    );
  }
  const targets = [
    [path.join(GENERATED_DIR, 'en.ts'), render('enWebMessages', en)],
    [path.join(GENERATED_DIR, 'ar.ts'), render('arWebMessages', ar)],
  ];
  if (check) {
    let ok = true;
    for (const [p, src] of targets) {
      if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== src) {
        ok = false;
        console.error(`DRIFT: ${path.relative(repoRoot, p)} — run the generator`);
      }
    }
    process.exit(ok ? 0 : 1);
  }
  fs.mkdirSync(GENERATED_DIR, { recursive: true });
  for (const [p, src] of targets) fs.writeFileSync(p, src);
  console.log(
    `generated ${path.relative(repoRoot, targets[0][0])} + ar (${Object.keys(en).length} keys)`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
